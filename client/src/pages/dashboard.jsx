import React, { useEffect, useState } from 'react';
import { Link } from 'react-router-dom';
import { analyticsApi } from '../api/analytics';
import StatusBadge from '../components/StatusBadge';

export default function Dashboard() {
  const [data, setData] = useState(null);
  const [isLoading, setIsLoading] = useState(true);
  const [error, setError] = useState(null);

  useEffect(() => {
    const fetchAnalytics = async () => {
      try {
        setIsLoading(true);
        const result = await analyticsApi.getDashboardAnalytics();
        setData(result);
      } catch (err) {
        console.error("Failed to load dashboard analytics:", err);
        setError("Failed to load real-time analytics.");
      } finally {
        setIsLoading(false);
      }
    };

    fetchAnalytics();
  }, []);

  const stats = [
    {
      id: 'repos',
      label: 'Total Repositories',
      count: data?.totalRepos ?? 0,
      subtext: 'Connected Repositories',
      link: '/repositories',
    },
    {
      id: 'prs',
      label: 'Total Pull Requests',
      count: data?.totalPrs ?? 0,
      subtext: 'Active Repositories',
      link: '/pull-requests',
    },
    {
      id: 'tracked',
      label: 'Tracked PRs',
      count: data?.totalTrackedPrs ?? 0,
      subtext: 'Monitored Sessions',
      link: '/tracked-issues',
    },
    {
      id: 'ai-reviews',
      label: 'AI Reviews Completed',
      count: data?.totalAiReviews ?? 0,
      subtext: 'Generated by AI Agent',
      link: '/pull-requests',
    },
    {
      id: 'ai-issues',
      label: 'AI Issues Flagged',
      count: data?.totalAiIssues ?? 0,
      subtext: 'Security & Code Smells',
      link: '/tracked-issues',
    },
    {
      id: 'confidence',
      label: 'Avg AI Confidence',
      count: `${data?.averageConfidenceScore || 0}%`,
      subtext: 'Agent Accuracy Metric',
      link: '/pull-requests',
    },
  ];

  return (
    <div className="space-y-6">
      {/* Page Title & Intro */}
      <div className="flex flex-col sm:flex-row sm:items-center sm:justify-between border-b border-gray-200 pb-4">
        <div>
          <h1 className="text-xl font-bold text-gray-900 tracking-tight">System Overview</h1>
          <p className="text-xs text-gray-500 mt-0.5">
            Real-time status of connected repositories, PR review metrics, and GitSight AI review agent.
          </p>
        </div>
        <div className="mt-3 sm:mt-0 flex space-x-2">
          <Link
            to="/repositories"
            className="px-3 py-1.5 text-xs font-medium bg-gray-900 hover:bg-black text-white rounded transition-colors shadow-sm"
          >
            Manage Repositories
          </Link>
          <Link
            to="/pull-requests"
            className="px-3 py-1.5 text-xs font-medium bg-white hover:bg-gray-50 text-gray-700 border border-gray-300 rounded transition-colors"
          >
            View Active PRs
          </Link>
        </div>
      </div>

      {/* Metric Cards Grid */}
      <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 xl:grid-cols-6 gap-4">
        {stats.map((stat) => (
          <div
            key={stat.id}
            className="bg-white p-4 flex flex-col justify-between hover:border-gray-300 transition-colors"
          >
            <div className="flex items-center justify-between">
              <span className="text-[11px] font-semibold text-gray-500 uppercase tracking-wider">
                {stat.label}
              </span>
              <div className={`w-7 h-7 rounded-md ${stat.bgColor} ${stat.color} flex items-center justify-center text-xs`}>
                <i className={stat.icon}></i>
              </div>
            </div>

            <div className="mt-3">
              <div className="text-2xl font-black text-gray-900 tracking-tight">
                {isLoading ? (
                  <div className="h-7 w-12 bg-gray-200 rounded animate-pulse"></div>
                ) : (
                  stat.count
                )}
              </div>
              <p className="text-[11px] text-gray-400 mt-1 flex items-center justify-between">
                <span>{stat.subtext}</span>
                {stat.link && (
                  <Link to={stat.link} className="text-blue-600 hover:underline font-medium">
                    View &rarr;
                  </Link>
                )}
              </p>
            </div>
          </div>
        ))}
      </div>

      {/* Recent Pull Requests Section */}
      <div className="space-y-3">
        <div className="flex items-center justify-between">
          <div>
            <h2 className="text-sm font-bold text-gray-900 uppercase tracking-wider">Recent Pull Requests</h2>
            <p className="text-xs text-gray-500 mt-0.5">
              Latest incoming PRs analyzed or awaiting review from your connected repositories.
            </p>
          </div>
          <Link
            to="/pull-requests"
            className="text-xs font-semibold text-blue-600 hover:text-blue-800 hover:underline"
          >
            See all PRs &rarr;
          </Link>
        </div>

        {/* Bordered Content Container (from table heading onwards) */}
        <div className="bg-white border border-gray-200 rounded shadow-xs overflow-hidden">
          {isLoading ? (
          <div className="p-6 space-y-4">
            {[1, 2, 3].map((i) => (
              <div key={i} className="animate-pulse flex items-center justify-between py-2 border-b border-gray-50">
                <div className="space-y-2 w-1/2">
                  <div className="h-4 bg-gray-200 rounded w-3/4"></div>
                  <div className="h-3 bg-gray-100 rounded w-1/3"></div>
                </div>
                <div className="h-6 bg-gray-100 rounded w-20"></div>
              </div>
            ))}
          </div>
        ) : data?.recentPrs && data.recentPrs.length > 0 ? (
          <div className="overflow-x-auto">
            <table className="w-full text-left text-xs">
              <thead className="bg-gray-50/75 border-b border-gray-100 text-gray-500 font-semibold uppercase tracking-wider">
                <tr>
                  <th className="px-5 py-3">Pull Request</th>
                  <th className="px-5 py-3">Repository</th>
                  <th className="px-5 py-3">Status</th>
                  <th className="px-5 py-3">AI Review</th>
                  <th className="px-5 py-3 text-right">Action</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-gray-100">
                {data.recentPrs.map((pr) => {
                  const repoFullName = pr.repositoryFullName || (pr.htmlUrl && pr.htmlUrl.split('github.com/')[1]?.split('/pull')[0]) || "repo";
                  return (
                    <tr key={`${repoFullName}-${pr.prNumber}`} className="hover:bg-gray-50/50 transition-colors">
                      <td className="px-5 py-3.5 max-w-xs sm:max-w-md">
                        <Link
                          to={`/pr-detail?repo=${encodeURIComponent(repoFullName)}&pr=${pr.prNumber}`}
                          className="font-semibold text-gray-900 hover:text-blue-600 transition-colors truncate block"
                          title={pr.title}
                        >
                          {pr.title}
                          <span className="ml-1.5 font-normal text-gray-400">#{pr.prNumber}</span>
                        </Link>
                        <div className="text-[11px] text-gray-500 mt-0.5 flex items-center space-x-2">
                          <span>by {pr.author}</span>
                          <span>&bull;</span>
                          <span>{new Date(pr.createdAt).toLocaleDateString()}</span>
                        </div>
                      </td>
                      <td className="px-5 py-3.5">
                        <Link
                          to={`/pull-requests?id=${encodeURIComponent(pr.repositoryId || pr.gitHubRepoId || repoFullName)}`}
                          className="font-mono text-[11px] text-blue-600 hover:text-blue-800 hover:underline transition-colors font-medium inline-block"
                          title={`View pull requests for ${repoFullName}`}
                        >
                          {repoFullName}
                        </Link>
                      </td>
                      <td className="px-5 py-3.5">
                        <StatusBadge state={pr.state} mergedAt={pr.mergedAt} isDraft={pr.isDraft} />
                      </td>
                      <td className="px-5 py-3.5">
                        {pr.analysisStatus === 'completed' ? (
                          <div className="inline-flex items-center space-x-1.5">
                            <span className="px-2 py-0.5 rounded-full text-[10px] font-bold bg-emerald-100 text-emerald-800 border border-emerald-200">
                              Analyzed
                            </span>
                            {pr.riskLevel && (
                              <span
                                className={`px-2 py-0.5 rounded-full text-[10px] font-bold ${
                                  pr.riskLevel === 'High'
                                    ? 'bg-rose-100 text-rose-800 border border-rose-200'
                                    : pr.riskLevel === 'Medium'
                                    ? 'bg-amber-100 text-amber-800 border border-amber-200'
                                    : 'bg-blue-100 text-blue-800 border border-blue-200'
                                }`}
                              >
                                {pr.riskLevel} Risk
                              </span>
                            )}
                          </div>
                        ) : pr.analysisStatus === 'analyzing' ? (
                          <span className="inline-flex items-center space-x-1 px-2 py-0.5 rounded-full text-[10px] font-bold bg-blue-50 text-blue-700 border border-blue-200">
                            <i className="fa-solid fa-spinner fa-spin text-[9px]"></i>
                            <span>Analyzing</span>
                          </span>
                        ) : (
                          <span className="px-2 py-0.5 rounded-full text-[10px] font-medium bg-gray-100 text-gray-600 border border-gray-200">
                            Pending
                          </span>
                        )}
                      </td>
                      <td className="px-5 py-3.5 text-right">
                        <Link
                          to={`/pr-detail?repo=${encodeURIComponent(repoFullName)}&pr=${pr.prNumber}`}
                          className="inline-flex items-center space-x-1 text-xs font-semibold text-blue-600 hover:text-blue-800 hover:underline"
                        >
                          <span>View PR</span>
                          <span>&rarr;</span>
                        </Link>
                      </td>
                    </tr>
                  );
                })}
              </tbody>
            </table>
          </div>
        ) : (
          <div className="p-8 text-center space-y-3">
            <div className="w-10 h-10 rounded-full bg-gray-100 text-gray-400 mx-auto flex items-center justify-center text-sm">
              <i className="fa-solid fa-code-pull-request"></i>
            </div>
            <p className="text-xs text-gray-500 font-medium">No pull requests found yet across your connected repositories.</p>
            <Link
              to="/repositories"
              className="inline-block text-xs font-semibold text-blue-600 hover:underline"
            >
              Check connected repositories &rarr;
            </Link>
          </div>
        )}
      </div>
    </div>
  </div>
);
}