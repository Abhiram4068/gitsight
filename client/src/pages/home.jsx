import React, { useEffect, useState } from "react";
import { Link } from "react-router-dom";
import { analyticsApi } from "../api/analytics";
import authApi from "../api/auth";
import StatusBadge from "../components/StatusBadge";

export default function Dashboard() {
  const [data, setData] = useState(null);
  const [isRuleSet, setIsRuleSet] = useState(null);
  const [isLoading, setIsLoading] = useState(true);
  const [error, setError] = useState(null);

  const [showWebhookInstructions, setShowWebhookInstructions] = useState(false);
  const [copiedWebhookUrl, setCopiedWebhookUrl] = useState(false);

  const handleCopyWebhookUrl = () => {
    navigator.clipboard.writeText("https://api.gitsight.app/webhooks/github");
    setCopiedWebhookUrl(true);
    setTimeout(() => setCopiedWebhookUrl(false), 2000);
  };

  useEffect(() => {
    const fetchAnalytics = async () => {
      try {
        setIsLoading(true);
        const [result, userProfile] = await Promise.allSettled([
          analyticsApi.getDashboardAnalytics(),
          authApi.getCurrentUser(),
        ]);

        if (result.status === "fulfilled") {
          setData(result.value);
        }
        if (userProfile.status === "fulfilled" && userProfile.value) {
          setIsRuleSet(userProfile.value.isRuleSet ?? false);
        }
      } catch (err) {
        console.error("Failed to load dashboard analytics:", err);
        setError("Failed to load real-time analytics.");
      } finally {
        setIsLoading(false);
      }
    };

    fetchAnalytics();
  }, []);

  const stats = [
    {
      id: "repos",
      label: "Total Repositories",
      count: data?.totalRepos ?? 0,
      subtext: "Connected Repositories",
      link: "/repositories",
    },
    {
      id: "prs",
      label: "Total Pull Requests",
      count: data?.totalPrs ?? 0,
      subtext: "Active Repositories",
      link: "/pull-requests",
    },
    {
      id: "tracked",
      label: "Tracked PRs",
      count: data?.totalTrackedPrs ?? 0,
      subtext: "Monitored Sessions",
      link: "/tracked-issues",
    },
    {
      id: "ai-reviews",
      label: "AI Reviews Completed",
      count: data?.totalAiReviews ?? 0,
      subtext: "Generated by AI Agent",
      link: "/pull-requests",
    },
  ];

  return (
    <div className="space-y-6">
      {/* Page Title & Intro */}
      <div className="flex flex-col sm:flex-row sm:items-center sm:justify-between border-b border-gray-200 pb-4">
        <div>
          <h1 className="text-xl font-bold text-blue-700 tracking-tight">
            Quick Insights
          </h1>
          <p className="text-xs text-gray-500 mt-0.5">
            Real-time status of connected repositories, PR review metrics, and
            GitSight AI review agent.
          </p>
        </div>
        <div className="mt-3 sm:mt-0 flex space-x-2">
          <Link
            to="/repositories"
            className="px-3 py-1.5 text-xs font-medium bg-gray-900 hover:bg-black text-white rounded transition-colors shadow-sm"
          >
            Manage Repositories
          </Link>
          <Link
            to="/pull-requests"
            className="px-3 py-1.5 text-xs font-medium bg-white hover:bg-gray-50 text-gray-700 border border-gray-300 rounded transition-colors"
          >
            View Active PRs
          </Link>
        </div>
      </div>

      {/* Amber Warning: Custom Review Rules (shown only when no custom rules are set) */}
      {isRuleSet === false && (
        <div className="bg-amber-50/90 border border-amber-200 p-3.5 sm:p-4 text-xs text-amber-900 flex flex-col sm:flex-row sm:items-center justify-between gap-3 shadow-2xs">
          <div className="flex items-start sm:items-center space-x-3">
            <div className="w-8 h-8 rounded-full flex items-center justify-center shrink-0 text-amber-600 mt-0.5 sm:mt-0">
              <i className="fa-solid fa-triangle-exclamation text-sm"></i>
            </div>
            <div>
              <p className="font-semibold text-amber-950 text-xs">
                No custom review rules configured
              </p>
              <p className="text-amber-800 text-[11px] mt-0.5 leading-relaxed">
                Your AI PR reviews are currently running in standard mode and
                evaluating everything without repository-specific guidelines. Set
                custom rules to enforce strict policies or suppress unwanted
                suggestions.
              </p>
            </div>
          </div>
          <Link
            to="/review-rules"
            className="text-xs font-semibold text-amber-900 hover:text-amber-950 hover:underline inline-flex items-center space-x-1 shrink-0 self-start sm:self-auto cursor-pointer"
          >
            <span>Configure Rules</span>
            <span>&rarr;</span>
          </Link>
        </div>
      )}

      {/* GitHub Webhook Setup Instructions Toggle */}
      <div className={`border-b border-gray-200 transition-all ${showWebhookInstructions ? 'pb-4' : 'pb-2'}`}>
        <button
          type="button"
          onClick={() => setShowWebhookInstructions(!showWebhookInstructions)}
          className="flex items-center justify-between text-xs font-bold text-gray-950 hover:text-black transition-colors cursor-pointer w-full text-left group bg-transparent border-0 p-0"
        >
          <div className="flex items-center space-x-2">
            <i className="fa-solid fa-bolt text-black text-xs"></i>
            <span className="text-gray-950 group-hover:text-black transition-colors">
              How to automate your open PR reviews using GitHub Webhooks ?  
            </span>
          </div>
          <i className={`fa-solid fa-chevron-${showWebhookInstructions ? 'up' : 'down'} text-gray-700 group-hover:text-black text-xs transition-transform`}></i>
        </button>

        <div
          className={`grid transition-all duration-300 ease-in-out ${
            showWebhookInstructions ? 'grid-rows-[1fr] opacity-100 mt-3' : 'grid-rows-[0fr] opacity-0 mt-0'
          }`}
        >
          <div className="overflow-hidden">
            <div className="pt-2 text-xs text-gray-700 space-y-3">
              <h3 className="font-bold text-sm text-gray-900 flex items-center space-x-2">
                <i className="fa-brands fa-github text-base text-gray-800"></i>
                <span>GitHub Setup Instructions</span>
              </h3>
              <ol className="list-decimal pl-5 space-y-2.5 font-medium leading-relaxed text-gray-700">
                <li>Navigate to your GitHub Repository and click on <strong className="text-gray-900 font-semibold">Settings</strong>.</li>
                <li>Select <strong className="text-gray-900 font-semibold">Webhooks</strong> from the left sidebar and click the <strong className="text-gray-900 font-semibold">Add webhook</strong> button.</li>
                <li>
                  <div className="flex items-center flex-wrap gap-2 mt-1">
                    <span>Set the <span className="font-semibold text-gray-900">Payload URL</span> to your GitSight endpoint:</span>
                    <div className="flex items-center space-x-1 max-w-full">
                      <code className="px-1.5 py-0.5 text-[11px] select-all text-blue-600 font-mono break-all">
                        https://gitsight-uwys.onrender.com/api/webhooks/github
                      </code>
                      <button
                        type="button"
                        onClick={handleCopyWebhookUrl}
                        className="p-1 hover:bg-gray-200 rounded text-gray-600 hover:text-gray-900 transition-colors cursor-pointer"
                        title="Copy to clipboard"
                      >
                        <i className={`fa-solid ${copiedWebhookUrl ? 'fa-check text-green-600' : 'fa-copy'}`}></i>
                      </button>
                    </div>
                  </div>
                </li>
                <li>Set <span className="font-semibold text-gray-900">Content type</span> to <strong className="text-gray-900 font-semibold">application/json</strong>.</li>
                <li>Under &quot;Which events would you like to trigger this webhook?&quot;, select <strong className="text-gray-900 font-semibold">Let me select individual events</strong>.</li>
                <li>Check the boxes for <strong className="text-gray-900 font-semibold">Pull requests</strong> .</li>
                <li>Click <strong className="text-gray-900 font-semibold">Add webhook</strong> to save your configuration.</li>
              </ol>
              <div className="mt-3 pt-3 border-t border-gray-100 flex items-center space-x-2 text-gray-500">
                <i className="fa-solid fa-circle-info text-blue-500"></i>
                <p className="italic">
                  Once configured, GitSight will automatically trigger AI reviews on newly opened or synchronized pull requests!
                </p>
              </div>
            </div>
          </div>
        </div>
      </div>

      {/* Metric Cards Grid */}
      <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 xl:grid-cols-4 gap-4">
        {stats.map((stat) => (
          <div
            key={stat.id}
            className="bg-white p-4 flex flex-col justify-between hover:border-gray-300 transition-colors"
          >
            <div className="flex items-center justify-between">
              <span className="text-[11px] font-semibold text-gray-500 uppercase tracking-wider">
                {stat.label}
              </span>
              {stat.link && (
                <Link
                  to={stat.link}
                  className="text-xs text-blue-600 hover:text-blue-800 hover:underline font-medium inline-flex items-center space-x-1"
                >
                  <span>View</span>
                  <span>&rarr;</span>
                </Link>
              )}
            </div>

            <div className="mt-3">
              <div className="text-2xl font-black text-gray-900 tracking-tight">
                {isLoading ? (
                  <div className="h-7 w-12 bg-gray-200 rounded animate-pulse"></div>
                ) : (
                  stat.count
                )}
              </div>
              <p className="text-[11px] text-gray-400 mt-1">
                {stat.subtext}
              </p>
            </div>
          </div>
        ))}
      </div>

      {/* Recent Pull Requests Section */}
      <div className="space-y-3">
        <div className="flex items-center justify-between">
          <div>
            <h2 className="text-xl font-bold text-blue-700  tracking-light">
              Recent Pull Requests
            </h2>
            <p className="text-xs text-gray-500 mt-0.5">
              Latest incoming PRs analyzed or awaiting review from your
              connected repositories.
            </p>
          </div>
          <Link
            to="/pull-requests"
            className="text-xs font-semibold text-blue-600 hover:text-blue-800 hover:underline"
          >
            See all PRs &rarr;
          </Link>
        </div>

        {/* Bordered Content Container (from table heading onwards) */}
        <div className="border border-gray-200 overflow-hidden shadow-xs bg-white flex flex-col">
          {/* Mobile Card View (md:hidden) */}
          <div className="block md:hidden divide-y divide-gray-100">
            {isLoading ? (
              <div className="py-14 text-center text-xs text-gray-500">
                <div className="w-5 h-5 border-2 border-gray-300 border-t-gray-800 rounded-full animate-spin mx-auto mb-2"></div>
                Fetching recent pull requests...
              </div>
            ) : data?.recentPrs && data.recentPrs.length > 0 ? (
              data.recentPrs.map((pr) => {
                const repoFullName =
                  pr.repositoryFullName ||
                  (pr.htmlUrl &&
                    pr.htmlUrl
                      .split("github.com/")[1]
                      ?.split("/pull")[0]) ||
                  "repo";

                return (
                  <div key={`${repoFullName}-${pr.prNumber}`} className="p-3.5 hover:bg-gray-50/70 transition-colors flex flex-col gap-2 text-xs">
                    <div className="flex items-center justify-between gap-2">
                      <div className="flex items-center space-x-2 min-w-0">
                        <Link
                          to={`/pr-detail?repo=${encodeURIComponent(repoFullName)}&pr=${pr.prNumber}`}
                          className="font-mono font-bold text-blue-600 hover:underline shrink-0"
                        >
                          #{pr.prNumber}
                        </Link>
                        <StatusBadge
                          state={pr.state}
                          mergedAt={pr.mergedAt}
                          isDraft={pr.isDraft}
                        />
                      </div>

                      <div className="shrink-0">
                        {pr.analysisStatus === "completed" || pr.analysisStatus === "analyzed" ? (
                          <span className="px-2 py-0.5 text-[10px] font-semibold text-emerald-800 bg-emerald-100 rounded-full inline-flex items-center border border-emerald-200 shadow-xs">
                            Analyzed
                          </span>
                        ) : pr.analysisStatus === "analyzing" ? (
                          <span className="px-2 py-0.5 text-[10px] font-semibold text-blue-800 bg-blue-100 border border-blue-200 rounded-full inline-flex items-center shadow-xs">
                            <div className="w-1.5 h-1.5 border-[1.5px] border-blue-400 border-t-blue-800 rounded-full animate-spin mr-1"></div>
                            Analyzing
                          </span>
                        ) : pr.analysisStatus === "failed" ? (
                          <span className="px-2 py-0.5 text-[10px] font-semibold text-red-800 bg-red-100 border border-red-200 rounded-full inline-flex items-center shadow-xs">
                            Failed
                          </span>
                        ) : (
                          <span className="px-2 py-0.5 text-[10px] font-semibold text-gray-700 bg-gray-100 border border-gray-200 rounded-full inline-flex items-center shadow-xs">
                            Pending
                          </span>
                        )}
                      </div>
                    </div>

                    <Link
                      to={`/pr-detail?repo=${encodeURIComponent(repoFullName)}&pr=${pr.prNumber}`}
                      className="font-semibold text-gray-900 hover:text-blue-600 transition-colors line-clamp-2"
                      title={pr.title}
                    >
                      {pr.title}
                    </Link>

                    <div className="flex items-center justify-between pt-1 border-t border-gray-100 text-gray-500">
                      <div className="flex items-center space-x-1.5 min-w-0">
                        <Link
                          to={`/pull-requests?id=${encodeURIComponent(pr.repositoryId || pr.gitHubRepoId || repoFullName)}`}
                          className="font-mono text-[11px] text-blue-600 hover:underline truncate max-w-[140px]"
                          title={repoFullName}
                        >
                          {repoFullName}
                        </Link>
                        <span>&bull;</span>
                        <span className="text-[11px] truncate">{pr.author}</span>
                      </div>

                      <Link
                        to={`/pr-detail?repo=${encodeURIComponent(repoFullName)}&pr=${pr.prNumber}`}
                        className="text-xs font-semibold text-blue-600 hover:text-blue-800 bg-blue-50 hover:bg-blue-100 px-2.5 py-0.5 rounded transition-colors shrink-0"
                      >
                        View &rarr;
                      </Link>
                    </div>
                  </div>
                );
              })
            ) : (
              <div className="py-14 text-center text-xs text-gray-500 px-4">
                <i className="fa-solid fa-code-pull-request text-2xl text-gray-300 mb-2 block"></i>
                No pull requests found yet across your connected repositories.
                <div className="mt-2">
                  <Link
                    to="/repositories"
                    className="inline-block text-xs font-semibold text-blue-600 hover:underline"
                  >
                    Check connected repositories &rarr;
                  </Link>
                </div>
              </div>
            )}
          </div>

          {/* Desktop Table View (hidden md:block) */}
          <div className="hidden md:block overflow-x-auto">
            <table className="w-full text-left border-collapse bg-white text-sm">
              <thead className="sticky top-0 z-10 bg-gray-50 border-b border-gray-200 text-gray-600 font-semibold select-none shadow-[0_1px_2px_rgba(0,0,0,0.03)] text-xs">
                <tr>
                  <th className="py-2.5 px-3">Pull Request</th>
                  <th className="py-2.5 px-3">Repository</th>
                  <th className="py-2.5 px-3">Status</th>
                  <th className="py-2.5 px-3">AI Review</th>
                  <th className="py-2.5 px-3 text-right">Action</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-gray-100 text-gray-700 text-xs">
                {isLoading ? (
                  <tr>
                    <td colSpan="5" className="py-14 text-center text-xs text-gray-500">
                      <div className="w-5 h-5 border-2 border-gray-300 border-t-gray-800 rounded-full animate-spin mx-auto mb-2"></div>
                      Fetching recent pull requests...
                    </td>
                  </tr>
                ) : data?.recentPrs && data.recentPrs.length > 0 ? (
                  data.recentPrs.map((pr) => {
                    const repoFullName =
                      pr.repositoryFullName ||
                      (pr.htmlUrl &&
                        pr.htmlUrl
                          .split("github.com/")[1]
                          ?.split("/pull")[0]) ||
                      "repo";
                    return (
                      <tr
                        key={`${repoFullName}-${pr.prNumber}`}
                        className="hover:bg-gray-50/70 transition-colors"
                      >
                        <td className="py-2.5 px-3 max-w-xs sm:max-w-md">
                          <Link
                            to={`/pr-detail?repo=${encodeURIComponent(repoFullName)}&pr=${pr.prNumber}`}
                            className="font-semibold text-gray-900 hover:text-blue-600 transition-colors truncate block"
                            title={pr.title}
                          >
                            {pr.title}
                            <span className="ml-1.5 font-normal text-gray-400">
                              #{pr.prNumber}
                            </span>
                          </Link>
                          <div className="text-[11px] text-gray-500 mt-0.5 flex items-center space-x-2">
                            <span>by {pr.author}</span>
                            <span>&bull;</span>
                            <span>
                              {new Date(pr.createdAt).toLocaleDateString()}
                            </span>
                          </div>
                        </td>
                        <td className="py-2.5 px-3 whitespace-nowrap">
                          <Link
                            to={`/pull-requests?id=${encodeURIComponent(pr.repositoryId || pr.gitHubRepoId || repoFullName)}`}
                            className="font-mono text-[11px] text-blue-600 hover:text-blue-800 hover:underline transition-colors font-medium inline-block"
                            title={`View pull requests for ${repoFullName}`}
                          >
                            {repoFullName}
                          </Link>
                        </td>
                        <td className="py-2.5 px-3 whitespace-nowrap">
                          <StatusBadge
                            state={pr.state}
                            mergedAt={pr.mergedAt}
                            isDraft={pr.isDraft}
                          />
                        </td>
                        <td className="py-2.5 px-3 whitespace-nowrap">
                          {pr.analysisStatus === "completed" || pr.analysisStatus === "analyzed" ? (
                            <span className="w-[76px] py-0.5 text-[11px] font-semibold text-emerald-800 bg-emerald-100 rounded-full inline-flex items-center justify-center border border-emerald-200 shadow-xs">
                              Analyzed
                            </span>
                          ) : pr.analysisStatus === "analyzing" ? (
                            <span className="w-[76px] py-0.5 text-[11px] font-semibold text-blue-800 bg-blue-100 border border-blue-200 rounded-full inline-flex items-center justify-center shadow-xs">
                              <div className="w-2 h-2 border-[1.5px] border-blue-400 border-t-blue-800 rounded-full animate-spin mr-1.5"></div>
                              Analyzing
                            </span>
                          ) : pr.analysisStatus === "failed" ? (
                            <span className="w-[76px] py-0.5 text-[11px] font-semibold text-red-800 bg-red-100 border border-red-200 rounded-full inline-flex items-center justify-center shadow-xs">
                              Failed
                            </span>
                          ) : (
                            <span className="w-[76px] py-0.5 text-[11px] font-semibold text-gray-700 bg-gray-100 border border-gray-200 rounded-full inline-flex items-center justify-center shadow-xs">
                              Pending
                            </span>
                          )}
                        </td>
                        <td className="py-2.5 px-3 text-right whitespace-nowrap">
                          <Link
                            to={`/pr-detail?repo=${encodeURIComponent(repoFullName)}&pr=${pr.prNumber}`}
                            className="text-xs font-medium text-blue-600 hover:text-blue-800 hover:underline cursor-pointer"
                          >
                            <span>View PR</span>
                            <span className="ml-1">&rarr;</span>
                          </Link>
                        </td>
                      </tr>
                    );
                  })
                ) : (
                  <tr>
                    <td colSpan="5" className="py-14 text-center text-xs text-gray-500">
                      <div className="w-10 h-10 text-gray-400 mx-auto flex items-center justify-center text-sm mb-2">
                        <i className="fa-solid fa-code-pull-request"></i>
                      </div>
                      No pull requests found yet across your connected repositories.
                      <div className="mt-2">
                        <Link
                          to="/repositories"
                          className="inline-block text-xs font-semibold text-blue-600 hover:underline"
                        >
                          Check connected repositories &rarr;
                        </Link>
                      </div>
                    </td>
                  </tr>
                )}
              </tbody>
            </table>
          </div>
        </div>
      </div>
    </div>
  );
}
